interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

function isLocale(value: string | null): value is Locale {
  return value === "en" || value === "tr";
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const storedLocale = getLocalStorageValue(LOCALE_STORAGE_KEY);
    if (isLocale(storedLocale)) setLocaleState(storedLocale);
    document.documentElement.lang = isLocale(storedLocale) ? storedLocale : "en";
  }, []);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    setLocalStorageValue(LOCALE_STORAGE_KEY, nextLocale);
    document.documentElement.lang = nextLocale;
  }, []);

  const t = useCallback((key: TranslationKey) => messages[locale][key], [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("Missing LocaleProvider");
  return context;
}

export function translateNavGroup(id: number, locale: Locale, fallback: string | undefined) {
  const key = id === 1 ? "navFunctions" : id === 2 ? "navSystem" : undefined;
  return key ? messages[locale][key] : fallback;
}

export function translateNavItem(id: string, locale: Locale, fallback: string) {
  const key = navItemKeys[id];
  return key ? messages[locale][key] : fallback;
}
